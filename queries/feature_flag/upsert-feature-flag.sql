-- ============================================================================
-- UPSERT FEATURE FLAG: create or update a feature flag by filling three slots
-- ============================================================================
--
-- WHY:
--   One place to set a feature flag without going through the admin app.
--   Every query below has the same three slots to fill in:
--     (1) feature name   (2) value   (3) the list of ids
--   Fill them, run it, done. A flag that already exists is updated in place,
--   a missing one is created. Running the same query twice never makes a
--   duplicate row.
--
-- TABLE public.feature_flag (one row per entity + feature):
--   id            text               uuid, generated by the query
--   workspace_id  text               workspace.id (Clerk org id)  - set for WORKSPACE flags
--   pharmacy_id   text               pharmacy.id  (Clerk org id)  - set for PHARMACY flags
--   entity_type   "EntityType"       WORKSPACE | PHARMACY | SYSTEM
--   feature_name  text               one of the keys listed below
--   value         "FeatureFlagValue" ENABLE | DISABLE | EXCLUSIVE
--   created_at    timestamp
--   updated_at    timestamp
--
--   Uniqueness is one row per (workspace_id, feature_name) and one row per
--   (pharmacy_id, feature_name). Both are unique INDEXES, not constraints,
--   which is what ON CONFLICT below relies on (step 0 confirms they exist).
--
-- POSSIBLE KEYS (feature_name):
--   feature_name is free text in the DB. These are the names the admin app
--   and the backend actually read. A typo creates a flag that nothing uses.
--
--   entity_type = 'WORKSPACE'   (covered entity / health center, uses workspace_id)
--     eligibility
--     encounter_claims
--     mastra_ai
--     referral_claim
--
--   entity_type = 'PHARMACY'    (uses pharmacy_id)
--     auto_order
--     broken_package
--     carve_in
--     integration_with_pos
--     mastra_ai
--     ndc_substitute
--     pending_claims
--     referral_claim
--     staff
--
--   entity_type = 'SYSTEM' exists in the enum but no feature_flag row uses it.
--   mastra_ai and referral_claim exist at both levels, so the same feature
--   name can be a workspace flag and a pharmacy flag at the same time.
--
-- POSSIBLE VALUES (value):
--   ENABLE     feature on
--   DISABLE    feature off. The admin app seeds every flag as DISABLE when a
--              workspace or pharmacy is created, so the usual job here is
--              flipping a row that already exists.
--   EXCLUSIVE  only meaningful for the WORKSPACE 'eligibility' flag. The
--              console then shows the eligibility module only (sidebar hides
--              everything else and / redirects to /eligibility). Every check
--              for "enabled" treats EXCLUSIVE the same as ENABLE. The admin
--              app offers EXCLUSIVE for workspace flags only, pharmacy flags
--              take ENABLE / DISABLE.
--
-- HOW TO RUN:
--   Step 0  preflight: both unique indexes and both enums (expect 2 rows each).
--   Step 1  look up the entity and its current flags before changing anything.
--   Step 2  WORKSPACE: set one feature to one value for a list of workspaces.
--           Creates the row if missing, updates it if present.
--   Step 3  PHARMACY: the same for a list of pharmacies.
--   Step 4  UPDATE only: same slots, but never creates a row.
--   Step 5  "only these": make the pasted ids the only ones with a feature on.
--   Step 6  verify.
--   Step 7  optional: several different features and values in one run.
--
--   Every writing query ends with RETURNING, so it prints the rows it wrote.
--   If an id you pasted is missing from that output, that id does not exist.
--   An existing row keeps its id, only value and updated_at change.
--
-- EXPECTED RESULT SHAPE (steps 2 to 5):
--   workspace_id (or pharmacy_id) | feature_name | value
--   one row per id that was written.
-- ============================================================================


-- ----------------------------------------------------------------------------
-- STEP 0: preflight - the two unique indexes ON CONFLICT needs (expect 2 rows)
--         and the allowed enum labels (expect 2 rows)
-- ----------------------------------------------------------------------------
SELECT indexname, indexdef
FROM pg_indexes
WHERE tablename = 'feature_flag'
  AND indexname IN ('feature_flag_workspace_id_feature_name_key',
                    'feature_flag_pharmacy_id_feature_name_key');

SELECT t.typname, array_agg(e.enumlabel ORDER BY e.enumsortorder) AS allowed_values
FROM pg_type t
JOIN pg_enum e ON e.enumtypid = t.oid
WHERE t.typname IN ('EntityType', 'FeatureFlagValue')
GROUP BY t.typname;


-- ----------------------------------------------------------------------------
-- STEP 1: look up the entity and what it has today
-- ----------------------------------------------------------------------------
-- workspace (covered entity): search by id or by name
SELECT w.id AS workspace_id, w."coveredEntityName", w."isDeleted",
       ff.feature_name, ff.value, ff.updated_at
FROM workspace w
LEFT JOIN feature_flag ff ON ff.workspace_id = w.id
WHERE w.id = 'org_xxxxxxxxxxxxxxxx'
   -- OR w."coveredEntityName" ILIKE '%part of the name%'
ORDER BY ff.feature_name;

-- pharmacy: search by id or by name
SELECT p.id AS pharmacy_id, p.pharmacy_name,
       ff.feature_name, ff.value, ff.updated_at
FROM pharmacy p
LEFT JOIN feature_flag ff ON ff.pharmacy_id = p.id
WHERE p.id = 'org_xxxxxxxxxxxxxxxx'
   -- OR p.pharmacy_name ILIKE '%part of the name%'
ORDER BY ff.feature_name;


-- ----------------------------------------------------------------------------
-- STEP 2: WORKSPACE - create or update one feature for a list of workspaces
--         fill in:  (1) feature name   (2) value   (3) workspace ids
-- ----------------------------------------------------------------------------
INSERT INTO feature_flag (id, workspace_id, feature_name, value, entity_type, created_at, updated_at)
SELECT gen_random_uuid()::text, w.id,
       'encounter_claims',               -- (1) feature name
       'ENABLE',                         -- (2) value: ENABLE / DISABLE / EXCLUSIVE
       'WORKSPACE', now(), now()
FROM workspace w
WHERE w.id IN (                          -- (3) workspace ids, one per line
  'org_xxxxxxxxxxxxxxxx',
  'org_yyyyyyyyyyyyyyyy'
)
ON CONFLICT (workspace_id, feature_name)
DO UPDATE SET value = EXCLUDED.value, updated_at = now()
RETURNING workspace_id, feature_name, value;


-- ----------------------------------------------------------------------------
-- STEP 3: PHARMACY - create or update one feature for a list of pharmacies
--         fill in:  (1) feature name   (2) value   (3) pharmacy ids
-- ----------------------------------------------------------------------------
INSERT INTO feature_flag (id, pharmacy_id, feature_name, value, entity_type, created_at, updated_at)
SELECT gen_random_uuid()::text, p.id,
       'ndc_substitute',                 -- (1) feature name
       'ENABLE',                         -- (2) value: ENABLE / DISABLE
       'PHARMACY', now(), now()
FROM pharmacy p
WHERE p.id IN (                          -- (3) pharmacy ids, one per line
  'org_xxxxxxxxxxxxxxxx',
  'org_yyyyyyyyyyyyyyyy'
)
ON CONFLICT (pharmacy_id, feature_name)
DO UPDATE SET value = EXCLUDED.value, updated_at = now()
RETURNING pharmacy_id, feature_name, value;


-- ----------------------------------------------------------------------------
-- STEP 4: UPDATE only - same three slots, but never creates a row.
--         Prints 0 rows if none of the ids has that flag yet.
-- ----------------------------------------------------------------------------
-- workspace flags
UPDATE feature_flag
SET value = 'DISABLE', updated_at = now()  -- (2) value
WHERE feature_name = 'encounter_claims'    -- (1) feature name
  AND workspace_id IN (                    -- (3) workspace ids
    'org_xxxxxxxxxxxxxxxx',
    'org_yyyyyyyyyyyyyyyy'
  )
RETURNING workspace_id, feature_name, value;

-- pharmacy flags
UPDATE feature_flag
SET value = 'DISABLE', updated_at = now()  -- (2) value
WHERE feature_name = 'ndc_substitute'      -- (1) feature name
  AND pharmacy_id IN (                     -- (3) pharmacy ids
    'org_xxxxxxxxxxxxxxxx',
    'org_yyyyyyyyyyyyyyyy'
  )
RETURNING pharmacy_id, feature_name, value;


-- ----------------------------------------------------------------------------
-- STEP 5: DISABLE - turn this feature off for the listed ids.
-- ----------------------------------------------------------------------------
-- workspace flags
UPDATE feature_flag
SET value = 'DISABLE', updated_at = now()
WHERE feature_name = 'encounter_claims'    -- (1) feature name
  AND entity_type  = 'WORKSPACE'
  AND value       <> 'DISABLE'
  AND workspace_id IN (                    -- (3) workspace ids to disable
    'org_xxxxxxxxxxxxxxxx',
    'org_yyyyyyyyyyyyyyyy'
  )
RETURNING workspace_id, feature_name, value;

-- pharmacy flags
UPDATE feature_flag
SET value = 'DISABLE', updated_at = now()
WHERE feature_name = 'ndc_substitute'      -- (1) feature name
  AND entity_type  = 'PHARMACY'
  AND value       <> 'DISABLE'
  AND pharmacy_id IN (                     -- (3) pharmacy ids to disable
    'org_xxxxxxxxxxxxxxxx',
    'org_yyyyyyyyyyyyyyyy'
  )
RETURNING pharmacy_id, feature_name, value;


-- ----------------------------------------------------------------------------
-- STEP 6: verify
-- ----------------------------------------------------------------------------
-- every entity that has this feature, with its name and value
-- feature names in dev DB (2026-10-29):
--   WORKSPACE: 'eligibility', 'encounter_claims', 'mastra_ai', 'referral_claim'
--   PHARMACY:  'auto_order', 'broken_package', 'carve_in', 'integration_with_pos',
--              'mastra_ai', 'ndc_substitute', 'pending_claims', 'referral_claim', 'staff'
SELECT ff.entity_type,
       ff.feature_name,
       COALESCE(ff.workspace_id, ff.pharmacy_id)        AS entity_id,
       COALESCE(w."coveredEntityName", p.pharmacy_name) AS entity_name,
       ff.value,
       ff.updated_at
FROM feature_flag ff
LEFT JOIN workspace w ON w.id = ff.workspace_id
LEFT JOIN pharmacy  p ON p.id = ff.pharmacy_id
WHERE ff.feature_name = 'encounter_claims'  -- (1) feature name
ORDER BY ff.entity_type, ff.value, entity_name;

-- totals per feature and value
SELECT entity_type, feature_name, value, count(*)::int AS rows
FROM feature_flag
GROUP BY entity_type, feature_name, value
ORDER BY entity_type, feature_name, value;

